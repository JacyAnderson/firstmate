#!/usr/bin/env bash
# fm-mission-control.sh - lifecycle for the Mission Control board server.
#
# The board is a small localhost-only node server that renders the captain's
# initiative cards from data/mission-control/ and queues captain input as
# inbox event files under state/mission-control/inbox/. docs/mission-control.md
# owns the file schemas and the server's wire contract; this script owns the
# launch/stop/status mechanics and the watcher-check installation.
#
# Usage:
#   fm-mission-control.sh start [--port N]   start the server (idempotent) and
#                                            install + register the inbox check
#   fm-mission-control.sh stop               stop the server (the inbox check
#                                            stays armed; queued input still
#                                            wakes firstmate)
#   fm-mission-control.sh status             report server and check state
#   fm-mission-control.sh install-check      (re)install and register only the
#                                            watcher inbox check
#   fm-mission-control.sh -h | --help        print this header
#
# Port resolution: --port, else FM_MC_PORT, else 7460. The server binds
# 127.0.0.1 only.
#
# Runtime records: state/mission-control/server.pid, state/mission-control/server.log.
# The inbox check is the standard registered custom check (AGENTS.md section 7):
# a mode-0700 shim at state/mission-control.check.sh, bound by
# bin/fm-check-register.sh, dispatching bin/fm-mission-control-poll.sh.
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-check-lib.sh
. "$SCRIPT_DIR/fm-check-lib.sh"

MC_STATE="$STATE/mission-control"
PID_FILE="$MC_STATE/server.pid"
LOG_FILE="$MC_STATE/server.log"
SERVER="$SCRIPT_DIR/fm-mission-control-server.mjs"
POLL="$SCRIPT_DIR/fm-mission-control-poll.sh"
CHECK_ID=mission-control
CHECK_FILE="$STATE/$CHECK_ID.check.sh"
PORT="${FM_MC_PORT:-7460}"

usage() {
  sed -n '2,27p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

server_pid() {
  local pid
  pid=$(cat "$PID_FILE" 2>/dev/null | tr -d '[:space:]')
  case "$pid" in ''|*[!0-9]*) return 1 ;; esac
  kill -0 "$pid" 2>/dev/null || return 1
  printf '%s' "$pid"
}

check_shim_content() {
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-mission-control.sh - mission-control inbox poll shim.' \
    '# The watcher validates these bytes against the check registration, then' \
    '# runs a private snapshot; the shim only dispatches the trusted poll script.' \
    "export FM_HOME=$(printf '%q' "$FM_HOME")" \
    "exec $(printf '%q' "$POLL")"
}

install_check() {
  mkdir -p "$STATE" || return 1
  if fm_custom_check_registered "$STATE" "$CHECK_ID" 2>/dev/null \
    && cmp -s "$CHECK_FILE" <(check_shim_content); then
    echo "inbox check: already registered"
    return 0
  fi
  umask 077
  local tmp
  tmp=$(mktemp "$STATE/.fm-mc-check.XXXXXX") || return 1
  check_shim_content > "$tmp" || { rm -f "$tmp"; return 1; }
  chmod 0700 "$tmp" || { rm -f "$tmp"; return 1; }
  mv -f "$tmp" "$CHECK_FILE" || { rm -f "$tmp"; return 1; }
  "$SCRIPT_DIR/fm-check-register.sh" "$CHECK_ID" || return 1
}

cmd_start() {
  command -v node >/dev/null 2>&1 || { echo "error: node is required to run the board server" >&2; exit 1; }
  [ -f "$SERVER" ] || { echo "error: server script missing: $SERVER" >&2; exit 1; }
  mkdir -p "$MC_STATE/inbox" "$FM_HOME/data/mission-control/initiatives" || exit 1
  install_check || { echo "error: inbox check installation failed" >&2; exit 1; }
  local pid
  if pid=$(server_pid); then
    echo "already running (pid $pid) - board: http://127.0.0.1:$PORT/"
    return 0
  fi
  FM_HOME="$FM_HOME" FM_MC_PORT="$PORT" nohup node "$SERVER" >> "$LOG_FILE" 2>&1 &
  pid=$!
  printf '%s\n' "$pid" > "$PID_FILE"
  local i=0
  while [ "$i" -lt 30 ]; do
    kill -0 "$pid" 2>/dev/null || {
      echo "error: server exited at startup; last log lines:" >&2
      tail -5 "$LOG_FILE" >&2 2>/dev/null
      rm -f "$PID_FILE"
      exit 1
    }
    if command -v curl >/dev/null 2>&1; then
      curl -sf -o /dev/null "http://127.0.0.1:$PORT/api/cards" 2>/dev/null && break
    else
      sleep 1
      break
    fi
    sleep 0.2
    i=$((i + 1))
  done
  echo "started (pid $pid) - board: http://127.0.0.1:$PORT/"
}

cmd_stop() {
  local pid
  if ! pid=$(server_pid); then
    rm -f "$PID_FILE"
    echo "not running"
    return 0
  fi
  kill "$pid" 2>/dev/null
  local i=0
  while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 50 ]; do
    sleep 0.1
    i=$((i + 1))
  done
  if kill -0 "$pid" 2>/dev/null; then
    kill -9 "$pid" 2>/dev/null
  fi
  rm -f "$PID_FILE"
  echo "stopped"
}

cmd_status() {
  local pid
  if pid=$(server_pid); then
    echo "server: running (pid $pid) - board: http://127.0.0.1:$PORT/"
  else
    echo "server: stopped"
  fi
  if fm_custom_check_registered "$STATE" "$CHECK_ID" 2>/dev/null; then
    echo "inbox check: registered"
  else
    echo "inbox check: not registered (run: fm-mission-control.sh install-check)"
  fi
  local pending
  pending=$(find "$MC_STATE/inbox" -name '*.msg' -type f 2>/dev/null | wc -l | tr -d ' ')
  echo "inbox: ${pending:-0} pending"
}

CMD="${1:-}"
[ "$#" -gt 0 ] && shift
while [ "$#" -gt 0 ]; do
  case "$1" in
    --port)
      [ "$#" -gt 1 ] || { echo "error: --port requires a value" >&2; exit 2; }
      PORT=$2
      shift 2
      ;;
    *)
      echo "error: unknown argument: $1" >&2
      exit 2
      ;;
  esac
done
case "$PORT" in ''|*[!0-9]*) echo "error: invalid port: $PORT" >&2; exit 2 ;; esac

case "$CMD" in
  start) cmd_start ;;
  stop) cmd_stop ;;
  status) cmd_status ;;
  install-check) install_check || { echo "error: inbox check installation failed" >&2; exit 1; } ;;
  -h|--help|help|'') usage ;;
  *) echo "error: unknown command: $CMD" >&2; usage >&2; exit 2 ;;
esac
